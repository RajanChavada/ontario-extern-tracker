// Usage:
//   node scripts/build-dist.mjs [--umami-id <uuid>] [--gsc <token>] [--site https://<host>] [--out <dir>] [--allow-stale]
//   --site defaults to "origin" in site.json (https://ontarioexterns.ca). --out defaults to dist/.
//
// On Cloudflare Pages (CF_PAGES=1) settings come from build environment variables instead of flags:
//   UMAMI_WEBSITE_ID   Umami website UUID (set for Production only)
//   GSC_VERIFICATION   optional Search Console meta-tag value (not needed with DNS verification)
//   CF_PAGES_BRANCH    set by Cloudflare. Any branch other than "main" is a preview build: analytics are
//                      forced off and stale data only warns. Production (main) fails on stale or invalid data.
//
// Builds dist/: the only folder that is ever uploaded. It contains an explicit allow-list of public files.
// Research notes, docs, tests, scripts and git metadata are never copied.
// The build fails if the data is invalid, older than 2 days, or if dist/ contains anything that looks private.
import { readFileSync, writeFileSync, mkdirSync, rmSync, copyFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { validateData, ontarioToday, daysBetween } from '../assets/logic.js';

const root = new URL('../', import.meta.url).pathname;
const args = process.argv.slice(2);
const opt = k => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : null; };
const fail = m => { console.error(`BUILD FAILED: ${m}`); process.exit(1); };

const site = (opt('--site') || JSON.parse(readFileSync(root + 'site.json')).origin || '').replace(/\/$/, '');
if (!/^https:\/\/[a-z0-9.-]+$/.test(site)) fail('pass --site https://<host> (https, no path)');
const onPages = process.env.CF_PAGES === '1';
const branch = process.env.CF_PAGES_BRANCH || '';
const isPreview = onPages && branch !== 'main';
let umamiId = (opt('--umami-id') || process.env.UMAMI_WEBSITE_ID || '').trim();
if (isPreview && umamiId) { console.log(`preview build (${branch}): analytics forced OFF`); umamiId = ''; }
if (umamiId && !/^[0-9a-f-]{36}$/i.test(umamiId)) fail('--umami-id must be the website UUID from Umami');
const gsc = (opt('--gsc') || process.env.GSC_VERIFICATION || '').trim();
if (gsc && !/^[A-Za-z0-9_-]{20,80}$/.test(gsc)) fail('--gsc must be the content value of the Search Console meta tag');
const host = new URL(site).hostname;
const umamiDomains = host.startsWith('www.') ? host : `${host},www.${host}`; // tracker only runs on these hosts (never pages.dev, previews or localhost)

// 1. Data gate
const data = JSON.parse(readFileSync(root + 'data/hospitals.json'));
const problems = validateData(data);
if (problems.length) fail('data problems:\n  ' + problems.join('\n  '));
const today = process.env.ET_TODAY || ontarioToday(); // ET_TODAY: tests only
const age = daysBetween(data.dataset_checked, today);
if (age > 2 && isPreview) console.warn(`WARNING (preview only): data last checked ${data.dataset_checked}, ${age} days ago`);
else if (age > 2 && !args.includes('--allow-stale')) fail(`data last checked ${data.dataset_checked} (${age} days ago). Re-verify (REFRESH.md) before deploying.`);
const oldest = data.entries.map(e => e.last_verified).sort()[0];

// 2. Calendar files from the current data
execFileSync(process.execPath, [root + 'scripts/build-ics.mjs'], { stdio: 'inherit' });

// 3. Copy the allow-list
const dist = (opt('--out') ? new URL(opt('--out').replace(/\/?$/, '/'), 'file://' + process.cwd() + '/').pathname : root + 'dist/');
rmSync(dist, { recursive: true, force: true });
const PUBLIC = [
  'index.html', 'what-is-a-clinical-extern-ontario.html', '404.html', 'favicon.svg',
  'assets/app.js', 'assets/logic.js', 'assets/analytics.js', 'assets/article.js', 'assets/styles.css',
  'data/hospitals.json',
  // Only calendar files for entries that still have a closing date (a removed posting must not leave a stale .ics behind).
  ...readdirSync(root + 'cal').filter(f => f.endsWith('.ics') && data.entries.some(e => e.deadline && `${e.id}.ics` === f)).map(f => 'cal/' + f),
];
for (const f of PUBLIC) { mkdirSync(dist + f.split('/').slice(0, -1).join('/'), { recursive: true }); copyFileSync(root + f, dist + f); }

// Public data copy: drop the internal maintainer note.
const { note: _internalNote, ...publicData } = data;
writeFileSync(dist + 'data/hospitals.json', JSON.stringify(publicData, null, 1) + '\n');

// 4. Production config (no debug logging; analytics only if an id was given)
writeFileSync(dist + 'assets/config.js', `// Generated by scripts/build-dist.mjs on ${today}. Do not edit in dist/.
export const CONFIG = {
  UMAMI_SRC: ${JSON.stringify(umamiId ? 'https://cloud.umami.is/script.js' : '')},
  UMAMI_WEBSITE_ID: ${JSON.stringify(umamiId)},
  UMAMI_DOMAINS: ${JSON.stringify(umamiDomains)},
  FEEDBACK_EMAIL: '',
  DEBUG: false,
};
`);

// 5. Head tags: canonical, Open Graph, analytics tag, Search Console verification
const umamiTag = umamiId
  ? `\n  <script defer src="https://cloud.umami.is/script.js" data-website-id="${umamiId}" data-domains="${umamiDomains}" data-do-not-track="true"></script>` : '';
const gscTag = gsc ? `\n  <meta name="google-site-verification" content="${gsc}">` : '';
const pages = [
  { file: 'index.html', path: '/' },
  { file: 'what-is-a-clinical-extern-ontario.html', path: '/what-is-a-clinical-extern-ontario' }, // Pages serves .html files at the extensionless URL (308 from .html)
];
for (const p of pages) {
  let html = readFileSync(dist + p.file, 'utf8');
  const title = html.match(/<title>([^<]+)<\/title>/)[1];
  const desc = html.match(/<meta name="description" content="([^"]+)"/)[1];
  const tags = `
  <link rel="canonical" href="${site}${p.path}">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="Ontario Extern Tracker">
  <meta property="og:title" content="${title}">
  <meta property="og:description" content="${desc}">
  <meta property="og:url" content="${site}${p.path}">
  <meta name="twitter:card" content="summary">${gscTag}${umamiTag}`;
  html = html.replace('<link rel="stylesheet"', tags.trimStart() + '\n  <link rel="stylesheet"');
  // Link straight to the final URLs so clicks don't go through a redirect.
  html = html.replaceAll('href="what-is-a-clinical-extern-ontario.html"', 'href="/what-is-a-clinical-extern-ontario"').replaceAll('href="./"', 'href="/"');
  writeFileSync(dist + p.file, html);
}

// 6. robots.txt, sitemap.xml, Cloudflare Pages _headers
writeFileSync(dist + 'robots.txt', `User-agent: *\nAllow: /\n\nSitemap: ${site}/sitemap.xml\n`);
writeFileSync(dist + 'sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${pages.map(p => `  <url><loc>${site}${p.path}</loc><lastmod>${data.dataset_checked}</lastmod></url>`).join('\n')}
</urlset>
`);
const csp = [
  "default-src 'self'",
  "script-src 'self' https://cloud.umami.is",
  "connect-src 'self' https://gateway.umami.is https://cloud.umami.is",
  "img-src 'self' data:",
  "style-src 'self'",
  "base-uri 'none'",
  "form-action 'none'",
  "frame-ancestors 'none'",
].join('; ');
writeFileSync(dist + '_headers', `/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), interest-cohort=()

# Only the real domain is indexed. The project's pages.dev address and its preview
# deployments (<hash>.<project>.pages.dev) serve the same files, so they are noindex.
https://:project.pages.dev/*
  X-Robots-Tag: noindex

https://:version.:project.pages.dev/*
  X-Robots-Tag: noindex

/data/*
  Cache-Control: public, max-age=300, must-revalidate

/assets/*
  Cache-Control: public, max-age=300, must-revalidate

/cal/*
  Content-Type: text/calendar; charset=utf-8
  Cache-Control: public, max-age=300, must-revalidate
`);

// 6b. Short campaign links (/t1, /i1, ...) → home page with UTM tags. Source of truth: marketing/carousel/links.json.
const LINKS = JSON.parse(readFileSync(root + 'marketing/carousel/links.json'));
writeFileSync(dist + '_redirects', Object.entries(LINKS.links).flatMap(([k, l]) => {
  const to = `/?utm_source=${l.source}&utm_medium=${l.medium}&utm_campaign=${LINKS.campaign}&utm_content=${l.content}`;
  return [...new Set([k, k.toUpperCase()])].map(p => `/${p} ${to} 302`); // typed on a phone, "T1" may be capitalised
}).join('\n') + '\n');

// 7. Leak scan: only allow-listed files, nothing private inside them
const walk = d => readdirSync(d).flatMap(f => statSync(d + f).isDirectory() ? walk(d + f + '/') : [d + f]);
const files = walk(dist).map(f => f.slice(dist.length));
const allowed = new Set([...PUBLIC, 'assets/config.js', 'robots.txt', 'sitemap.xml', '_headers', '_redirects']);
const extra = files.filter(f => !allowed.has(f));
if (extra.length) fail('unexpected files in dist: ' + extra.join(', '));
const BAD = [/\/Users\/|\/home\/|[A-Z]:\\\\Users/, /research\//, /\.git\b/, /127\.0\.0\.1|localhost|192\.168\./, /DEBUG:\s*true/, /@[a-z0-9-]+\.(com|ca|org)\b/i];
// Optional extra patterns (e.g. names of unrelated private projects), one regex per line, kept out of git.
if (existsSync(root + '.leakscan.local')) for (const l of readFileSync(root + '.leakscan.local', 'utf8').split('\n').map(x => x.trim()).filter(x => x && !x.startsWith('#'))) BAD.push(new RegExp(l, 'i'));
for (const f of files) {
  const text = readFileSync(dist + f, 'utf8');
  for (const re of BAD) if (re.test(text)) fail(`${f} matches private pattern ${re}`);
}
if (/JobPosting/.test(readFileSync(dist + 'index.html', 'utf8'))) fail('JobPosting structured data must not be used');

console.log(`\ndist/ built for ${site}`);
console.log(`output: ${dist}${onPages ? ` (Cloudflare Pages, branch ${branch || '?'}, ${isPreview ? 'preview' : 'production'})` : ''}`);
if (onPages && !isPreview && !umamiId) console.warn('WARNING: production build without UMAMI_WEBSITE_ID: the site works but nothing is measured.');
console.log(`data checked ${data.dataset_checked} (oldest entry ${oldest}); analytics ${umamiId ? 'ON (' + umamiDomains + ' only)' : 'OFF (no --umami-id)'}; Search Console tag ${gsc ? 'included' : 'not included'}`);
let total = 0;
for (const f of files.sort()) { const n = statSync(dist + f).size; total += n; console.log(`  ${String(n).padStart(7)}  ${f}`); }
console.log(`  ${String(total).padStart(7)}  total bytes, ${files.length} files`);
